"""Refresh cadences of the registry sources and the list of builds that are due (brief 30
Track 3.1).

Each wave source carries `refresh` (daily | weekly | monthly | quarterly | yearly) and
`refresh_basis`: the publisher's own rhythm where it states one, otherwise the interval at
which we check a source that states none (the basis says which). Rules below, by kind and
host; a registry entry's own `refresh` wins. Wave 9's registry gets the fields written into
its entries (`assign`); wave 10's is generated by `probe_wave10.py registry`, which calls
`refresh_of`.

    uv run python scripts/freshness.py assign          # write refresh into wave9_sources.yaml
    uv run python scripts/freshness.py due [--max 40]  # the sources due, as wave9.yml groups
"""

from __future__ import annotations

import argparse
import json
import sys
from datetime import date, timedelta
from pathlib import Path
from typing import Any
from urllib.parse import urlparse

import yaml

ROOT = Path(__file__).resolve().parents[1]
DAYS = {"daily": 1, "weekly": 7, "monthly": 30, "quarterly": 91, "yearly": 365}
CHECK = "the publisher states no rhythm: checked {}"
# (kind or None, host suffix or None) -> (refresh, basis)
RULES: list[tuple[str | None, str | None, str, str]] = [
    (
        "wdi",
        None,
        "quarterly",
        "World Bank WDI is updated several times a year (its release notes)",
    ),
    (
        "eurostat_tsv",
        None,
        "monthly",
        "Eurostat updates a dataset when new data arrive (release calendar)",
    ),
    (
        None,
        "ec.europa.eu",
        "monthly",
        "Eurostat updates a dataset when new data arrive (release calendar)",
    ),
    (
        "census",
        None,
        "yearly",
        "ACS 5-year estimates are released each December (Census Bureau schedule)",
    ),
    ("fwf", "ncei.noaa.gov", "monthly", "NCEI Storm Events are updated monthly (NCEI)"),
    (
        "govuk",
        None,
        "yearly",
        "UK official statistics are released yearly (gov.uk release calendar)",
    ),
    (None, "nomisweb.co.uk", "yearly", "ONS/Nomis tables are released yearly"),
    ("arcgis", None, "monthly", CHECK.format("monthly (a live service)")),
    ("ckan", None, "monthly", CHECK.format("monthly (a live portal)")),
    (None, "opendatasoft.com", "monthly", CHECK.format("monthly (a live portal)")),
    (
        None,
        "emodnet",
        "quarterly",
        CHECK.format("quarterly (EMODnet adds national data as it arrives)"),
    ),
    (None, "eia.gov", "quarterly", CHECK.format("quarterly")),
    (None, "openei.org", "monthly", CHECK.format("monthly (a live database)")),
    ("raster", None, "yearly", CHECK.format("yearly (a modelled or survey product)")),
]
CENSUS_HOSTS = (
    "istat.it",
    "ine.es",
    "ine.pt",
    "statistik.at",
    "cso.ie",
    "destatis.de",
    "csu.gov.cz",
    "stat.fi",
)


def refresh_of(s: dict[str, Any]) -> tuple[str, str]:
    if s.get("refresh"):
        return s["refresh"], s.get("refresh_basis", "set in the registry")
    url = s.get("url") or (s.get("urls") or [""])[0]
    host = urlparse(url).netloc
    if any(host.endswith(h) for h in CENSUS_HOSTS) and s.get("fam") == "outlines":
        return "yearly", "census geography, redrawn with each census: checked yearly"
    for kind, h, every, basis in RULES:
        if (kind is None or s.get("kind") == kind) and (h is None or h in host):
            return every, basis
    return "quarterly", CHECK.format("quarterly")


def assign() -> None:
    """Add `refresh` and `refresh_basis` to every one-line entry of wave9_sources.yaml."""
    path = ROOT / "scripts" / "wave9_sources.yaml"
    lines = path.read_text(encoding="utf-8").split("\n")
    n = 0
    for i, line in enumerate(lines):
        if not line.startswith("  - {id:") or "refresh:" in line or not line.endswith("}"):
            continue
        s = yaml.safe_load(line[4:])
        every, basis = refresh_of(s)
        lines[i] = (
            line[:-1]
            + f", refresh: {every}, refresh_basis: '{basis.replace(chr(39), chr(39) * 2)}'}}"
        )
        n += 1
    path.write_text("\n".join(lines), encoding="utf-8")
    print(f"refresh written to {n} entries of {path.relative_to(ROOT)}")


def built_dates(wave: int) -> dict[str, str]:
    out: dict[str, str] = {}
    for f in sorted((ROOT / "data" / f"wave{wave}_built").glob("*.json")):
        for sid, b in json.loads(f.read_text(encoding="utf-8")).items():
            if b.get("built") and (b.get("rows") or b.get("raster")):
                out[sid] = max(out.get(sid, ""), b["built"])
    return out


def due(max_n: int, today: date | None = None) -> dict[int, list[str]]:
    """Per wave, the built sources whose last build is older than their cadence, oldest first."""
    today = today or date.today()
    out: dict[int, list[str]] = {}
    for wave in (9, 10):
        reg = ROOT / "scripts" / f"wave{wave}_sources.yaml"
        if not reg.exists():
            continue
        built = built_dates(wave)
        late = []
        for s in yaml.safe_load(reg.read_text(encoding="utf-8"))["sources"]:
            if s.get("status") != "build" or s["id"] not in built:
                continue
            every, _ = refresh_of(s)
            last = date.fromisoformat(built[s["id"]])
            if last + timedelta(days=DAYS[every]) <= today:
                late.append((last, s["id"]))
        out[wave] = [sid for _, sid in sorted(late)][:max_n]
    return out


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("what", choices=["assign", "due"])
    ap.add_argument("--max", type=int, default=40, help="sources per wave and run")
    a = ap.parse_args()
    if a.what == "assign":
        assign()
        return
    for wave, ids in due(a.max).items():
        if ids:
            # one line per wave: the groups wave9.yml takes (s:<id> builds one source)
            print(f"{wave} " + " ".join(f"s:{i}" for i in ids))
        else:
            print(f"{wave}", file=sys.stderr)


if __name__ == "__main__":
    main()
