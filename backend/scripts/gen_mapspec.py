"""Generate agent/mapspec.schema.json and frontend/src/lib/mapspec.ts from agent/mapspec.py.

uv run python scripts/gen_mapspec.py          # write both files
uv run python scripts/gen_mapspec.py --check  # fail when either is stale (tests, CI)
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path
from typing import Any

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

from agent.mapspec import schema  # noqa: E402

ROOT = Path(__file__).resolve().parents[2]
SCHEMA_PATH = ROOT / "agent" / "mapspec.schema.json"
TS_PATH = ROOT / "frontend" / "src" / "lib" / "mapspec.ts"


def ts_type(s: dict[str, Any]) -> str:
    if "$ref" in s:
        return s["$ref"].rsplit("/", 1)[-1]
    if "const" in s:
        return json.dumps(s["const"])
    if "enum" in s:
        return " | ".join(json.dumps(v) for v in s["enum"])
    if "anyOf" in s:
        return " | ".join(dict.fromkeys(ts_type(x) for x in s["anyOf"]))
    t = s.get("type")
    if t == "array":
        if "prefixItems" in s:
            return "[" + ", ".join(ts_type(x) for x in s["prefixItems"]) + "]"
        inner = ts_type(s.get("items", {}))
        return f"({inner})[]" if "|" in inner else f"{inner}[]"
    if t == "object":
        ap = s.get("additionalProperties")
        if isinstance(ap, dict):
            return f"Record<string, {ts_type(ap)}>"
        return "Record<string, unknown>"
    return {
        "string": "string",
        "number": "number",
        "integer": "number",
        "boolean": "boolean",
        "null": "null",
    }.get(t or "", "unknown")


def interface(name: str, s: dict[str, Any]) -> str:
    lines = []
    if s.get("description"):
        lines.append("/** " + " ".join(s["description"].split()) + " */")
    lines.append(f"export interface {name} {{")
    required = set(s.get("required", []))
    for prop, ps in s.get("properties", {}).items():
        if ps.get("description"):
            lines.append("  /** " + " ".join(ps["description"].split()) + " */")
        opt = "" if prop in required else "?"
        lines.append(f"  {prop}{opt}: {ts_type(ps)};")
    lines.append("}")
    return "\n".join(lines)


def typescript(sch: dict[str, Any]) -> str:
    out = [
        "// Generated by backend/scripts/gen_mapspec.py from backend/agent/mapspec.py.",
        "// Do not edit by hand.",
        "// The MapSpec and ChartSpec the agent sends (docs/AGENT.md section 5).",
        "",
    ]
    for name, s in sorted(sch["$defs"].items()):
        out.append(interface(name, s))
        out.append("")
    return "\n".join(out)


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    a = ap.parse_args()
    sch = schema()
    files = {SCHEMA_PATH: json.dumps(sch, indent=2) + "\n", TS_PATH: typescript(sch)}
    stale = [p for p, text in files.items() if not p.exists() or p.read_text() != text]
    if a.check:
        for p in stale:
            print(f"stale: {p.relative_to(ROOT)} (run uv run python scripts/gen_mapspec.py)")
        return 1 if stale else 0
    for p, text in files.items():
        p.write_text(text)
        print(f"wrote {p.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
